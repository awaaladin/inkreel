// Generates TypeScript types from ../schemas/*.schema.json (which come from the Pydantic models). Never hand-write these.
import fs from 'node:fs';
import { compile } from 'json-schema-to-typescript';
const dir = '../schemas';
let out = '// GENERATED by scripts/gen-types.mjs from Pydantic JSON Schema - do not edit\n';
for (const f of fs.readdirSync(dir).filter(f => f.endsWith('.schema.json')).sort()) {
  const schema = JSON.parse(fs.readFileSync(`${dir}/${f}`, 'utf8'));
  out += await compile(schema, schema.title || f, { bannerComment: '', additionalProperties: false, declareExternallyReferenced: true, unreachableDefinitions: false });
}
fs.mkdirSync('src/types', { recursive: true });
fs.writeFileSync('src/types/model.d.ts', out);
console.log('types generated');
