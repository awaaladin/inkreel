// tokens.json is the single source; this writes tokens.css (CSS variables, both themes) and tokens.ts (typed access).
import fs from 'node:fs';
const t = JSON.parse(fs.readFileSync('src/design/tokens.json', 'utf8'));
const kebab = s => s.replace(/[A-Z]/g, m => '-' + m.toLowerCase());
const colors = (c) => Object.entries(c).map(([k, v]) => `  --c-${kebab(k)}: ${v};`).join('\n');
const shadows = (e) => Object.entries(e).map(([k, v]) => `  --e-${k}: ${v};`).join('\n');
const flat = (prefix, o) => Object.entries(o).map(([k, v]) => `  --${prefix}-${k}: ${v};`).join('\n');
const css = `/* GENERATED by scripts/gen-tokens.mjs from tokens.json - do not edit */
:root, :root[data-theme="dark"] {
${colors(t.color.dark)}
${shadows(t.elevation.dark)}
  color-scheme: dark;
}
:root[data-theme="light"] {
${colors(t.color.light)}
${shadows(t.elevation.light)}
  color-scheme: light;
}
@media (prefers-color-scheme: light) {
  :root:not([data-theme]) {
${colors(t.color.light)}
${shadows(t.elevation.light)}
    color-scheme: light;
  }
}
:root {
${flat('s', t.space)}
${flat('r', t.radius)}
${flat('font', t.font)}
${flat('t', t.type)}
${flat('d', t.motion.duration)}
${flat('ease', t.motion.easing)}
}
`;
fs.writeFileSync('src/design/tokens.css', css);
const ts = `// GENERATED by scripts/gen-tokens.mjs from tokens.json - do not edit
export const tokens = ${JSON.stringify(t, null, 2)} as const;
export type SpringName = keyof typeof tokens.motion.spring;
export const springs = tokens.motion.spring;
export type ThemeName = 'dark' | 'light';
`;
fs.writeFileSync('src/design/tokens.ts', ts);
console.log('tokens generated');
